# Mostrar resultados
print("OPERACIONES ARITMETICAS")

print("Numero 1:", numero1)
print("Numero 2:", numero2)

print("Suma:", suma)
print("Resta:", resta)
print("Multiplicacion:", multiplicacion)
print("Division:", division)
print("Modulo:", modulo)

# Operaciones con decimales
print("\nOPERACIONES CON DECIMALES")

